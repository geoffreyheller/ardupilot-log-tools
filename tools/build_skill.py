"""Generate the agent skill's reference files from the canonical docs.

    python tools/build_skill.py           # (re)write skills/ardupilot-log-analysis/
    python tools/build_skill.py --check   # exit 1, listing what differs, if it is stale

The repo's markdown is canonical; nothing under `references/` is edited by hand. This
copies each file in REFERENCES into the skill, rewrites the links between them to the
skill's own file names (a link to a document the skill leaves out becomes `alog docs X`,
which every install has), strips repository-development sections, and stamps a
do-not-edit header. In the hand-written SKILL.md it fills the regions between
`<!-- generated:NAME -->` and `<!-- /generated -->` from GUIDE.md, and sets the pinned
version in SKILL.md, the run scripts and the Claude Code marketplace entry
(`.claude-plugin/marketplace.json`, the one per-agent adapter, outside the skill folder) from
`dflog/__init__.py`.

Stdlib only. The output depends on nothing but the sources (no dates, no commit hashes),
so a second run changes nothing and `--check` can run in CI.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, "skills", "ardupilot-log-analysis")
REPO_URL = "https://github.com/geoffreyheller/ardupilot-log-tools"

# skill file -> canonical source, relative to the repo root
REFERENCES = {
    "rules.md": "RULES.md",
    "guide.md": "GUIDE.md",
    "recipes.md": "SKILLS.md",
    "pitfalls.md": "reference/pitfalls.md",
    "integrity-codes.md": "reference/integrity-codes.md",
    "json-output.md": "reference/json-output.md",
    "thresholds.md": "reference/thresholds.md",
    "messages.md": "reference/messages.md",
    "param-decodings.md": "reference/param-decodings.md",
    "current-sensor-calibration.md": "reference/current-sensor-calibration.md",
    "report-template.md": "templates/log-analysis-template.md",
}
# Repository-development sections, removed by heading (through the next heading of the
# same level). A heading that is no longer there is an error, not a silent no-op.
STRIP = {
    "RULES.md": ["## 5. Changing the tools."],
}
_TARGET = {src: dst for dst, src in REFERENCES.items()}


def _read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read().replace("\r\n", "\n")


def version():
    m = re.search(r'^__version__ = "([^"]+)"', _read(os.path.join(ROOT, "dflog", "__init__.py")), re.M)
    return m.group(1)


def git_ref(ver):
    """The git ref the run scripts fall back to: the release tag, or main for a dev build."""
    return "main" if re.search(r"(dev|a|b|rc)\d*$", ver) else f"v{ver}"


def relink(text, prefix):
    """Rewrite links to canonical docs as links inside the skill.

    `prefix` is how the referring file reaches references/: "" from inside it,
    "references/" from SKILL.md."""
    def ref(m):
        tick, name, close = m.group(1), m.group(2), m.group(3)
        src = f"reference/{name}.md"
        if src in _TARGET:
            return f"{tick}{prefix}{_TARGET[src]}{close}"
        return f"`alog docs {name}`"        # left out of the skill; every install has it
    text = re.sub(r"(`?)reference/([a-z0-9-]+)\.md(`?)", ref, text)
    text = text.replace("templates/log-analysis-template.md", prefix + "report-template.md")
    for src in ("RULES.md", "GUIDE.md", "SKILLS.md"):
        text = re.sub(r"(?<![\w/.-])" + re.escape(src), prefix + _TARGET[src], text)
    return text


def strip_sections(text, headings, source):
    for heading in headings:
        lines = text.split("\n")
        if heading not in lines:
            raise ValueError(f"{source}: heading {heading!r} to strip is not there; update STRIP")
        i = lines.index(heading)
        level = len(heading) - len(heading.lstrip("#"))
        j = next((k for k in range(i + 1, len(lines))
                  if re.match(r"#{1,%d} " % level, lines[k])), len(lines))
        while i > 0 and lines[i - 1].strip() in ("", "---"):     # the rule and blank lines above it
            i -= 1
        text = "\n".join(lines[:i] + lines[j:]).rstrip("\n") + "\n"
    return text


def header(source):
    return (f"<!-- Generated by tools/build_skill.py from {source} in {REPO_URL}. Do not edit:\n"
            f"     edit the source and rerun. Paths such as dflog/... refer to that repository. -->\n\n")


def reference_files():
    out = {}
    for dst, src in REFERENCES.items():
        text = _read(os.path.join(ROOT, src))
        text = strip_sections(text, STRIP.get(src, []), src)
        out[os.path.join("references", dst)] = header(src) + relink(text, "")
    return out


def _guide_section(n):
    guide = _read(os.path.join(ROOT, "GUIDE.md"))
    m = re.search(r"^## %d\. .*?$(.*?)(?=^## \d+\. |\Z)" % n, guide, re.M | re.S)
    if not m:
        raise ValueError(f"GUIDE.md has no section {n}")
    return m.group(1).strip("\n-").strip("\n")


def _tables(text):
    """Every markdown table in `text`, in order."""
    return [m.group(0).rstrip("\n") for m in re.finditer(r"(?:^\|.*\|[ \t]*\n?)+", text, re.M)]


def generated_regions():
    """NAME -> text for the `<!-- generated:NAME -->` regions of SKILL.md."""
    s2 = _guide_section(2)
    rules = s2[s2.index("1. **"):].rstrip()
    tables = _tables(_guide_section(3))
    if len(tables) < 2:
        raise ValueError("GUIDE.md §3 no longer has the window table and the --flight table")
    return {
        "ground-rules": relink(rules, "references/"),
        "window-table": relink(tables[0], "references/"),
        "flight-table": relink(tables[1], "references/"),
    }


def skill_md():
    path = os.path.join(SKILL, "SKILL.md")
    text = _read(path)
    for name, body in generated_regions().items():
        # The body may not run into the next region's start marker, so an empty region
        # can never swallow its neighbour.
        pat = re.compile(r"(<!-- generated:%s -->\n)(?:(?!<!-- generated:).)*?(<!-- /generated -->)"
                         % re.escape(name), re.S)
        if len(pat.findall(text)) != 1:
            raise ValueError(f"SKILL.md needs exactly one <!-- generated:{name} --> region")
        text = pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)
    text = re.sub(r'^(  version: )"[^"]*"$', lambda m: f'{m.group(1)}"{version()}"', text, count=1, flags=re.M)
    return text


def scripts():
    ver, ref = version(), git_ref(version())
    out = {}
    for rel, pin, gref in (("scripts/alog.sh", r'^PIN="[^"]*"$', r'^REF="[^"]*"$'),
                           ("scripts/alog.ps1", r"^\$Pin = '[^']*'$", r"^\$Ref = '[^']*'$")):
        text = _read(os.path.join(SKILL, rel))
        quote = '"' if rel.endswith(".sh") else "'"
        lhs_pin, lhs_ref = ("PIN=", "REF=") if rel.endswith(".sh") else ("$Pin = ", "$Ref = ")
        for pat, lhs, val in ((pin, lhs_pin, ver), (gref, lhs_ref, ref)):
            if not re.search(pat, text, re.M):
                raise ValueError(f"{rel}: no line matching {pat}")
            text = re.sub(pat, lambda m: f"{lhs}{quote}{val}{quote}", text, count=1, flags=re.M)
        out[rel] = text
    return out


def build():
    """{path relative to the skill folder: content} for every skill file this script owns."""
    files = reference_files()
    files["SKILL.md"] = skill_md()
    files.update(scripts())
    return files


def adapters():
    """{path relative to the repo root: content} for the per-agent files outside the skill."""
    rel = os.path.join(".claude-plugin", "marketplace.json")
    text = _read(os.path.join(ROOT, rel))
    if len(re.findall(r'^      "version": "[^"]*",$', text, re.M)) != 1:
        raise ValueError(f"{rel}: expected exactly one plugin entry with a \"version\"")
    text = re.sub(r'^(      "version": )"[^"]*",$', lambda m: f'{m.group(1)}"{version()}",', text, flags=re.M)
    return {rel: text}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if anything is stale")
    args = ap.parse_args(argv)
    files = build()
    stale = [rel for rel, text in sorted(files.items())
             if not os.path.isfile(os.path.join(SKILL, rel)) or _read(os.path.join(SKILL, rel)) != text]
    outside = adapters()
    stale_outside = [rel for rel, text in sorted(outside.items()) if _read(os.path.join(ROOT, rel)) != text]
    refdir = os.path.join(SKILL, "references")
    extra = sorted(os.path.join("references", f) for f in (os.listdir(refdir) if os.path.isdir(refdir) else [])
                   if os.path.join("references", f) not in files)
    if args.check:
        for rel in stale:
            print(f"stale: {rel}")
        for rel in stale_outside:
            print(f"stale: {rel} (repo root)")
        for rel in extra:
            print(f"not generated (delete it, or add it to REFERENCES): {rel}")
        if stale or stale_outside or extra:
            print("run `python tools/build_skill.py` and commit the result")
            return 1
        print(f"skill is current ({len(files)} files, {len(outside)} adapter)")
        return 0
    for rel in stale:
        path = os.path.join(SKILL, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(files[rel])
        print(f"wrote {rel}")
    for rel in stale_outside:
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(outside[rel])
        print(f"wrote {rel}")
    for rel in extra:
        os.remove(os.path.join(SKILL, rel))
        print(f"removed {rel}")
    print(f"{len(stale) + len(stale_outside)} written, {len(extra)} removed, "
          f"{len(files) + len(outside) - len(stale) - len(stale_outside)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
